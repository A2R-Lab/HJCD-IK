#!/usr/bin/env python3
"""Write a foam-format spherized Panda URDF carrying cuRobo's collision spheres.

HJCD compiles whatever sphere model `generate_grid.py --spherized-urdf` is given. Building it on cuRobo's
bundled 61-sphere model (franka.yml, Apache-2.0, NVIDIA) instead of foam's isolates the collision *model* from
the *solver* in collision-scene comparisons: the clearance ladder (2026-10-03) showed foam's spheres close gaps
the dataset's own solutions pass through (cage −1.5 cm: 0 % of mesh-feasible goal_ik accepted vs 68 % by
cuRobo's spheres), so HJCD/foam cannot be compared with cuRobo/its-spheres on tight scenes without this build.

The output keeps the kinematic URDF's links and joints (the codegen binds spheres by link name through the
joint tree) and replaces every <collision> with one sphere per cuRobo entry, centres in the link frame.

  python benchmark/make_curobo_sphere_urdf.py --out benchmark/reference/panda_curobo_spherized.urdf
  python scripts/codegen/generate_grid.py csrc/urdf/panda.urdf -t panda_hand_joint --collision \\
      --spherized-urdf benchmark/reference/panda_curobo_spherized.urdf && bash scripts/setup/rebuild.sh
"""
from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from panda_model import _KINEMATIC_URDF, curobo_franka_yml_path  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--urdf", default=str(_KINEMATIC_URDF), help="kinematic URDF whose links/joints to keep")
    ap.add_argument("--robot-yml", default="", help="cuRobo robot yml (default: the bundled franka.yml)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    import yaml
    yml = Path(args.robot_yml) if args.robot_yml else curobo_franka_yml_path()
    spheres = yaml.safe_load(open(yml))["robot_cfg"]["kinematics"]["collision_spheres"]
    tree = ET.parse(args.urdf)
    root = tree.getroot()
    links = {link.get("name"): link for link in root.findall("link")}
    missing = [l for l in spheres if l not in links and l != "attached_object"]
    if missing:
        sys.exit(f"links in {yml.name} but not in {args.urdf}: {missing}")
    n = 0
    for name, link in links.items():
        for col in link.findall("collision"):
            link.remove(col)
        for sp in spheres.get(name, []):
            if sp["radius"] <= 0:
                continue
            col = ET.SubElement(link, "collision")
            ET.SubElement(col, "origin", rpy="0 0 0", xyz=" ".join(f"{float(c):.6f}" for c in sp["center"]))
            ET.SubElement(ET.SubElement(col, "geometry"), "sphere", radius=f"{float(sp['radius']):.6f}")
            n += 1
    root.insert(0, ET.Comment(f" collision spheres: cuRobo {yml.name} (Apache-2.0, NVIDIA) on {Path(args.urdf).name}; "
                              f"generated by benchmark/make_curobo_sphere_urdf.py "))
    ET.indent(tree, space="  ")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    tree.write(args.out, xml_declaration=True, encoding="unicode")
    print(f"wrote {args.out}: {n} spheres on {sum(1 for l in spheres if spheres[l])} links")


if __name__ == "__main__":
    main()
