"""Illustrative seven-joint rail + UR5e, not a hardware-approved robot model.

Run from any directory: python /path/to/examples/rail_ur5e.py --cache /path/to/cache
First build needs hjcdik[build] and nvcc. No meshes or downloads are needed.
See docs/source/user_guide/tutorials/rail_ur5e.md for geometry and safety limits.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np
import hjcdik

NAME = "example-rail-ur5e"
TARGET = "flange-tool0"


def assemble(directory):
    """Reuse the shipped UR5e assets, changing only the world-to-base joint."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    preset = hjcdik.presets()["ur5e"]
    sources = (preset["urdf"], hjcdik.sphere_presets()[preset["spheres"]])
    paths = []
    for source, filename in zip(sources, ("rail_ur5e.urdf", "rail_ur5e_spheres.urdf")):
        source = Path(source)
        root = ET.parse(source).getroot()
        root.set("name", "illustrative_rail_ur5e")
        joint = root.find("joint[@name='base_joint']")
        if joint is None or joint.get("type") != "fixed":
            raise ValueError("expected the shipped UR5e fixed base_joint")
        joint.set("name", "rail_joint")
        joint.set("type", "prismatic")
        ET.SubElement(joint, "axis", xyz="1 0 0")
        ET.SubElement(joint, "limit", lower="0", upper="1", effort="1000", velocity="1")
        # All supplied geometry, including base_link_inertia, is retained.
        # No invented carriage, stationary supports or extra contact exclusions.
        provenance = (
            "Generated by examples/rail_ur5e.py from " + source.name + "; sha256 "
            + hashlib.sha256(source.read_bytes()).hexdigest()
            + ". UR5e: UniversalRobots/Universal_Robots_ROS2_Description at "
            "22f055da2fa7e2158254426107d1f257fd56aebb, BSD-3-Clause. "
            "See ur5e-license.txt and the shipped ur5e_provenance.json. "
            "Illustrative X rail [0,1] m; no carriage/support geometry; not a safety certificate."
        )
        root.insert(0, ET.Comment(provenance))
        ET.indent(root, space="  ")
        path = directory / filename
        text = ET.tostring(root, encoding="unicode") + "\n"
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
        paths.append(path)
    license_path = Path(preset["urdf"]).parent.parent / "licenses/ur5e.txt"
    (directory / "ur5e-license.txt").write_text(license_path.read_text())
    return tuple(paths)


def journey(solver, targets, nearby, world, precision="fp32"):
    """One public-API workflow, reused by tests and the installed-wheel check.

    Warm only accurate rows; missing rows are reported, not replaced with NaNs.
    No assertion here equates returned count with successful IK.
    """
    solver.set_world(**world)
    options = dict(batch_size=2000, num_solutions=4, collision="hard", precision=precision)
    out = solver.solve(targets, **options)
    snapshot = out.q.copy()
    good = out.ok(5, .001)
    selected = np.flatnonzero(good.any(axis=1))
    warm = None
    if len(selected):
        first = good[selected].argmax(axis=1)
        seeds = out.q[selected, first, :][:, None, :]
        warm = solver.solve(nearby[selected], q_init=seeds, **options)
    solver.set_world(spheres=[[0, 0, 0, 100]])
    blocked = solver.solve(targets[:1], batch_size=37, num_solutions=4,
                           collision="hard", precision=precision)
    if not blocked[0].count:
        print("No qualifying solution found within the budget; no rows to index.")
    solver.set_world(**world)
    restored = solver.solve(targets[:1], **options)
    solver.clear_world()
    np.testing.assert_array_equal(out.q, snapshot)
    print(f"cold accurate: {len(selected)}/{len(targets)}; warm accurate: "
          f"{0 if warm is None else int(warm.ok(5, .001).any(axis=1).sum())}/{len(selected)}")
    return dict(out=out, warm=warm, selected=selected, blocked=blocked, restored=restored)


def run(cache_dir, precision="fp32", load_only=False):
    cache_dir = Path(cache_dir).resolve()
    if not load_only:
        urdf, spheres = assemble(cache_dir / "example-inputs")
        hjcdik.build(urdf, ee_link=TARGET, spheres=spheres, name=NAME, cache_dir=cache_dir)
    artifact = hjcdik.load(NAME, cache_dir=cache_dir)
    solver = hjcdik.Solver(NAME, cache_dir=cache_dir, allow_build=False)
    print(list(zip(solver.info.joint_names, solver.info.joint_units, solver.info.joint_limits)))
    data = json.loads(Path(__file__).with_name("rail_ur5e_targets.json").read_text())
    results = {}
    for name, cell in data["sets"].items():
        results[name] = journey(solver, np.array(cell["targets"]), np.array(cell["nearby_targets"]),
                                cell["world"], precision)
    return artifact, solver, results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--precision", choices=("fp32", "fp64"), default="fp32")
    parser.add_argument("--load-only", action="store_true")
    args = parser.parse_args()
    run(args.cache, args.precision, args.load_only)
