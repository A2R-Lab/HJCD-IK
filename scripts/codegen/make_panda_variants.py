#!/usr/bin/env python3
"""Deterministic, physically equivalent Panda fixtures for general-joint validation.

Run from a checkout with numpy and scipy (the dev extra). Re-expressing a link
changes every attached origin and its joint axis, not merely the next joint.
The sphere source is the shipped rebound model, with the same finger openings.
"""
import argparse
import copy
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[2]


def vector(text):
    return np.array([float(x) for x in text.split()])


def numbers(values):
    return " ".join(format(float(v), ".17g") for v in values)


def origin(element):
    node = element.find("origin")
    t = np.eye(4)
    if node is not None:
        t[:3, :3] = Rotation.from_euler("xyz", vector(node.get("rpy", "0 0 0"))).as_matrix()
        t[:3, 3] = vector(node.get("xyz", "0 0 0"))
    return t


def set_origin(element, transform):
    node = element.find("origin")
    if node is None:
        node = ET.SubElement(element, "origin")
    node.set("xyz", numbers(transform[:3, 3]))
    node.set("rpy", numbers(Rotation.from_matrix(transform[:3, :3]).as_euler("xyz")))


def reexpress(root):
    """F maps new coordinates to old coordinates; keep base and tool unchanged."""
    frames = {link.get("name"): np.eye(4) for link in root.findall("link")}
    for i, joint in enumerate(root.findall("joint")):
        if joint.get("type") in ("revolute", "continuous"):
            f = frames[joint.find("child").get("link")]
            f[:3, :3] = Rotation.from_euler("xyz", [0.17*(i+1), -0.23, 0.31]).as_matrix()
    for joint in root.findall("joint"):
        parent = frames[joint.find("parent").get("link")]
        child = frames[joint.find("child").get("link")]
        set_origin(joint, np.linalg.inv(parent) @ origin(joint) @ child)
        axis = joint.find("axis")
        if joint.get("type") != "fixed" and axis is not None:
            axis.set("xyz", numbers(child[:3, :3].T @ vector(axis.get("xyz"))))
    for link in root.findall("link"):
        f_inv = np.linalg.inv(frames[link.get("name")])
        for tag in ("inertial", "visual", "collision"):
            for attached in link.findall(tag):
                set_origin(attached, f_inv @ origin(attached))
    return root


def negate_axes(root):
    for joint in root.findall("joint"):
        if joint.get("type") in ("revolute", "continuous"):
            axis = joint.find("axis")
            axis.set("xyz", numbers(-vector(axis.get("xyz"))))
            limit = joint.find("limit")
            if limit is not None and "lower" in limit.attrib:
                low, high = float(limit.get("lower")), float(limit.get("upper"))
                limit.set("lower", format(-high, ".17g"))
                limit.set("upper", format(-low, ".17g"))
    return root


def add_slider(root, travel=0.5):
    ET.SubElement(root, "link", name="slider_base")
    link = root.find("link[@name='panda_link0']")
    if link.find("inertial") is None:
        inertial = ET.SubElement(link, "inertial")
        ET.SubElement(inertial, "mass", value="1")
        ET.SubElement(inertial, "inertia", ixx="1", iyy="1", izz="1", ixy="0", ixz="0", iyz="0")
    joint = ET.SubElement(root, "joint", name="slider", type="prismatic")
    ET.SubElement(joint, "parent", link="slider_base")
    ET.SubElement(joint, "child", link="panda_link0")
    ET.SubElement(joint, "axis", xyz="0 0 1")
    ET.SubElement(joint, "limit", lower="0", upper=format(travel, ".17g"), effort="100", velocity="1")
    return root


def generate(output):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    for name, source, transform in [
        ("panda_axes.urdf", "csrc/urdf/panda.urdf", reexpress),
        ("panda_axes_spheres.urdf", "csrc/collision/panda_foam_rebound.urdf", reexpress),
        ("panda_negz.urdf", "csrc/urdf/panda.urdf", negate_axes),
        ("panda_slider.urdf", "csrc/urdf/panda.urdf", add_slider),
    ]:
        path = ROOT / source
        tree = transform(copy.deepcopy(ET.parse(path).getroot()))
        ET.indent(tree, space="  ")
        provenance = f"<!-- Generated by make_panda_variants.py from {source}; sha256 {hashlib.sha256(path.read_bytes()).hexdigest()} -->\n"
        (output / name).write_text(provenance + ET.tostring(tree, encoding="unicode") + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "tests/robots")
    generate(parser.parse_args().output)
