"""Offline builder for the G1 collision sidecar (spec sections 3-5).

Two modes:
    build  (default): read the AUTHORED collision_sidecar/g1_proxy_model.yaml (the human-edited
                      source of truth), derive the pair policy from the URDF tree, and emit
                      generated/g1_collision_sidecar.json (topology + hashes, CPU/CUDA input).
    --seed:           (re)generate the YAML by fitting tight capsules/spheres to the URDF's own
                      collision geometry. Run ONCE to bootstrap; manual tuning then lives in the
                      YAML and `build` (no --seed) preserves it.

The proxy model is a compact union of spheres and capsules (tens of primitives), NOT the
598-sphere GRiD representation.

Pair policy (spec section 4): auto-disable ONLY same-link, direct parent-child, and
fixed-relative-transform (same rigid group) pairs -- each with a recorded reason. Nested pairs
are NOT blanket-disabled; they are resolved by tightening/splitting proxies in the YAML.

    HJCD-IK/.venv/bin/python collision_sidecar/build_collision_sidecar.py [--seed]
"""
